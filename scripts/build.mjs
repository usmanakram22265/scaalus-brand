// Builds dist/ from the token sources:
//   dist/brand.json  every reference resolved to hex, plus contrast tables (for agents)
//   dist/brand.js    the same data as window.SCAALUS (for the guidelines page)
//   dist/tokens.css  CSS custom properties, one [data-mood] block per mood
// Usage: node scripts/build.mjs
import fs from "node:fs";
import path from "node:path";
import { build, root } from "./lib/system.mjs";


const data = build();
const dist = path.join(root, "dist");
fs.mkdirSync(dist, { recursive: true });

const json = JSON.stringify(data, null, 2) + "\n";
fs.writeFileSync(path.join(dist, "brand.json"), json);
fs.writeFileSync(path.join(dist, "brand.js"), `// Generated by scripts/build.mjs — do not edit.\nwindow.SCAALUS = ${json.trimEnd()};\n`);

const lines = ["/* Generated by scripts/build.mjs — do not edit. Scaalus colour system v" + data.version + " */", ":root {"];
for (const [id, c] of Object.entries(data.palette)) lines.push(`  --sc-color-${id}: ${c.hex};`);
for (const [id, g] of Object.entries(data.gradients)) lines.push(`  --sc-gradient-${id}: ${g.css};`);
lines.push("}", "");
for (const m of Object.values(data.moods)) {
  lines.push(`/* ${m.name} · ${m.theme} · ${m.tagline} */`, `[data-mood="${m.id}"] {`);
  for (const [k, v] of Object.entries(m.css)) lines.push(`  ${k}: ${v};`);
  lines.push("}", "");
}
fs.writeFileSync(path.join(dist, "tokens.css"), lines.join("\n"));

const failing = Object.values(data.moods).filter((m) => !m.contrast.pass).map((m) => m.name);
console.log(`Built dist/ — ${Object.keys(data.palette).length} colours, ${Object.keys(data.gradients).length} gradients, ${Object.keys(data.moods).length} moods.`);
if (failing.length) console.log(`Contrast failures in: ${failing.join(", ")} — run node scripts/check-contrast.mjs`);
